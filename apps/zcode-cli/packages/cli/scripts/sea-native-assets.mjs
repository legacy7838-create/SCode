/**
 * Embeds the compiled `@zcode/rust` `.node` binaries into a SEA blob.
 *
 * A napi addon cannot be `require()`-d out of a single-file blob — the blob is reached via
 * `sea.getRawAsset()`, not the filesystem. So the build embeds the raw bytes plus a
 * manifest carrying every sha256, and the runtime extracts them into a content-addressed
 * cache before the first `loadNative()` call (`src/sea-native-runtime.ts`).
 *
 * The file list and every hash come from `zcode-packaging sea-assets`, which owns the
 * payload decision (docs/specs/rust-native-packaging.md). This module only stages and
 * embeds what the Rust tool named — it holds no crate list, no platform table, and no
 * tolerance, so a missing binary fails the build here rather than on a user's machine.
 */
import { spawnSync } from "node:child_process";
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";
import process from "node:process";

/** Must match `plan::SEA_MANIFEST_ASSET_KEY` in zcode-packaging. */
export const SEA_NATIVE_MANIFEST_ASSET_KEY = "native-manifest.json";

const stagingDirectoryForTarget = (dist, target) =>
  resolve(dist, "sea-assets", `${target}-native`);

/**
 * Produces the SEA `assets` entries for the native payload.
 *
 * Throws when the tool is missing, the plan is absent, or the tool exits non-zero. There is
 * no best-effort path: a SEA binary without its binaries throws at runtime on the first
 * `loadNative()`, so failing here is strictly better.
 */
export function prepareSeaNativeAssets({ dist, target, repoRoot }) {
  const stagingDirectory = stagingDirectoryForTarget(dist, target);
  mkdirSync(stagingDirectory, { recursive: true });

  const manifestPath = resolve(stagingDirectory, SEA_NATIVE_MANIFEST_ASSET_KEY);
  const assetsPath = resolve(stagingDirectory, "assets.json");

  // The tool builds its own plan from `--target` (which accepts this module's `win-*`
  // spelling), so neither side has to agree with a shell script about where a plan file
  // lives or what a platform is called.
  const result = spawnSync(
    "cargo",
    [
      "run",
      "--release",
      "-p",
      "zcode-packaging",
      "--",
      "sea-assets",
      "--target",
      target,
      "--out-manifest",
      manifestPath,
      "--assets-out",
      assetsPath,
    ],
    {
      cwd: resolve(repoRoot, "packages/rust"),
      stdio: "inherit",
      env: process.env,
    },
  );
  if (result.error) {
    throw new Error(
      `[sea-native-assets] could not run zcode-packaging: ${result.error.message}. ` +
        "A Rust toolchain is required to build the SEA blob (docs/specs/rust-native-packaging.md risk R6).",
    );
  }
  if (result.status !== 0) {
    throw new Error(
      `[sea-native-assets] zcode-packaging sea-assets failed (exit ${result.status}). ` +
        "Run `pnpm --filter @zcode/rust build:native` first so the binaries exist.",
    );
  }

  // The tool emits the `{ "<asset key>": "<source path>" }` map in the exact shape the SEA
  // config's `assets` field expects, so the two sides cannot drift.
  const assets = JSON.parse(readFileSync(assetsPath, "utf8"));
  const manifest = JSON.parse(readFileSync(manifestPath, "utf8"));
  if (!Array.isArray(manifest.files) || manifest.files.length === 0) {
    throw new Error("[sea-native-assets] manifest lists no native binaries");
  }

  // Keep the generated files out of the way of the tool's own re-runs.
  writeFileSync(
    resolve(stagingDirectory, "README.txt"),
    "Generated by zcode-packaging sea-assets. Do not edit; rebuild instead.\n",
  );

  return {
    assets,
    manifestKey: SEA_NATIVE_MANIFEST_ASSET_KEY,
    manifestPath,
    fileCount: manifest.files.length,
  };
}
