import type { JsonSchema } from "../model/index.js";
import type { TraceContext } from "../tracing/tracer.js";
import type { McpServerFailureKind, OfficialMcpAuthPortFailureReason } from "@zcode/shared";

export type McpServerTransportType = "stdio" | "http" | "sse";
export type McpProtocolVersion = "legacy" | "auto" | "2026-07-28";
export type McpServerIsolation = "session" | "workspace";

/** The runtime origin attached by the host after public MCP configuration validation completes. */
export interface McpServerRuntimeSource {
  kind: "builtin" | "plugin";
}

export interface McpServerConfigBase {
  enabled?: boolean;
  isolation?: McpServerIsolation;
  protocolVersion?: McpProtocolVersion;
  /** Host-generated only; the public configuration schema rejects this field. */
  source?: McpServerRuntimeSource;
  timeoutMs?: number;
}

export interface McpClientCredentialsOAuthConfig {
  type: "client_credentials";
  clientId: string;
  clientSecret: string;
  clientName?: string;
  scope?: string;
}

export interface McpAuthorizationCodeOAuthConfig {
  type: "authorization_code";
  clientId?: string;
  clientSecret?: string;
  clientName?: string;
  redirectPath?: string;
  scope?: string;
}

export type McpOAuthConfig = McpAuthorizationCodeOAuthConfig | McpClientCredentialsOAuthConfig;

/**
 * The authentication declaration of the official ZCode Server MCP.
 * Allowed with `type: "http"` and `type: "stdio"`; `sse` is still rejected.
 * Both `type` and `provider` are exact values; no aliases or case variants are accepted.
 *
 * Note: this field by itself is **not** proof of official identity. Official identity is decided by the runtime-resolved ZCode API origin
 * (the host side re-validates it too); a third-party Plugin that copies this field can only make credentials flow to the real ZCode backend.
 *
 * The two shapes deliver credentials over different channels:
 * - http: the host injects the identity headers per request inside a fetch wrapper, so credentials never enter the plugin process;
 * - stdio: the requests are issued by the plugin process itself, and the identity headers ride along in the `_meta` of every outbound protocol message.
 */
export interface ZCodeOfficialMcpAuthConfig {
  type: "zcode_official";
  provider: "jwt_token";
}

/**
 * Runtime ownership info generated by the Plugin loader; `.mcp.json` cannot override it.
 * It is used for credential resolution and log correlation, and plays no part in the trust decision.
 * The target origin must pass `isOfficialMcpOriginTrusted`; plugin identity itself is not
 * an authorization filter. Destination validation and the server-side interface-permission / plan / quota validations each carry a different boundary.
 */
export interface McpOfficialProvenance {
  pluginId: string;
  /** The raw MCP key inside a Plugin (without the `plugin:<name>:` namespace prefix). */
  mcpKey: string;
  source: "plugin";
}

export interface McpStdioServerConfig extends McpServerConfigBase {
  type: "stdio";
  command: string;
  args?: string[];
  cwd?: string;
  env?: Record<string, string>;
  auth?: ZCodeOfficialMcpAuthConfig;
  /** Host-generated; it must never come from file configuration. */
  official?: McpOfficialProvenance;
}

export interface McpHttpServerConfig extends McpServerConfigBase {
  type: "http";
  url: string;
  headers?: Record<string, string>;
  oauth?: McpOAuthConfig;
  auth?: ZCodeOfficialMcpAuthConfig;
  /** Host-generated; it must never come from file configuration. */
  official?: McpOfficialProvenance;
}

export interface McpSseServerConfig extends McpServerConfigBase {
  type: "sse";
  url: string;
  headers?: Record<string, string>;
  oauth?: McpOAuthConfig;
}

export type McpServerConfig = McpStdioServerConfig | McpHttpServerConfig | McpSseServerConfig;

export type McpServerStatusKind =
  | "connecting"
  | "connected"
  | "disabled"
  | "disconnected"
  | "failed"
  | "untrusted";

export interface McpServerStatus {
  status: McpServerStatusKind;
  transport: McpServerTransportType;
  toolCount: number;
  updatedAt: string;
  error?: string;
  failureKind?: McpServerFailureKind;
  serverRequestId?: string;
  protocolEra?: "legacy" | "modern";
  authorization?: {
    type: "oauth_authorization_code";
    authorizationUrl: string;
    startedAt: string;
  };
}

export interface McpToolAnnotations {
  readOnlyHint?: boolean;
  destructiveHint?: boolean;
  idempotentHint?: boolean;
  openWorldHint?: boolean;
}

