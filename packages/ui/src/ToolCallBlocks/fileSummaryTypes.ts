/**
 * All the workflow run facts the tool card in the chat area needs to render its run state. The host
 * computes them together when it joins the `workflowRuns` projection by `toolCallId`.
 *
 * Deliberately only these four fields: the card carries the **entry point and the summary**;
 * budget, event log, result, and failure panels all belong to the detail page.
 */
export interface WorkflowRunCardSummary {
  runId: string;
  /**
   * The id of the **CreateWorkflow row** that started this run (the projected `run.toolCallId`).
   * Any request that opens the side-pane run view must carry it — `WorkflowRunSidePane` uses this
   * id to look the starting row up in the row window (the causalityGraph and the script source text
   * both hang off that row). It is only populated in the byRunId join table (the key of the
   * byToolCallId table is this value); a resume row's own toolCallId is **not** this value (a
   * resume row's display has no graph).
   */
  toolCallId?: string;
  status: WorkflowRunState["status"];
  /** The reason for `stopped`; only carried when the projection carries it. */
  stopReason?: WorkflowRunState["stopReason"];
  /**
   * Number of settled nodes (`phase === "settled"`), **including** those that hit the cap and never
   * made it into the table.
   */
  nodesSettled: number;
  /**
   * Number of scheduled (observed) nodes, **not** an end-to-end total — for a dynamic workflow the
   * node count is decided by the script at run time, so no static total exists. Progress therefore
   * reads as "how many of the scheduled ones have settled", and never poses as a completion
   * percentage.
   *
   * Both numbers come from `workflowRunStepCounts` (@zcode/shared): the ones inside the `nodes`
   * table plus `usage.nodesUnlisted` for the ones outside it. A run that hit the 1024 cap still
   * reports its real step count here; what is missing is the **per-step detail**, which the card
   * and the detail page each call out with their own "details for only n/m steps" line.
   */
  nodesTotal: number;
  /**
   * Subagent count (the projected `run.actors.length`). The counts on the card cover only phases
   * and subagents.
   *
   * It is still optional: both join-table builders always fill it in, but the type does not require
   * it — once cold replay landed, the two journal-fallback merges were deleted, so today there is
   * no second producer; the consuming side stays tolerant of its absence and writes no count.
   */
  agents?: number;
  /**
   * This run in the live projection: the card builds its timeline model from it (lamps, pills,
   * ink). It is absent when the journal fallback hits — at that point only the status word exists,
   * so the timeline is drawn static.
   */
  run?: WorkflowRunState;
  /**
   * Resumable (a live projection `cancelled`, or a `resumable` that the journal summary computed
   * with the CLI's resume gate). The Resume in the card footer renders only when it is present; the
   * UI never derives it itself from status + failureCode.
   */
  resumable?: true;
}

/**
 * Where a CreateWorkflow / AmendWorkflow row sits in the compile-feedback loop. The host computes
 * it in one pass over the row window in row order (`v4/workflowDraftJoin.ts`); the renderer only
 * reads it.
 */
export interface WorkflowDraftPosition {
  /**
   * Which draft: within the same lineage and the same round, the nth submission since the last
   * compile, counting from 1.
   */
  ordinal: number;
  /**
   * When another row of the same lineage follows, the feedback row's empty ring lamp fades from the
   * warning color to a neutral one.
   */
  superseded: boolean;
}

