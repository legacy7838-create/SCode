// ConversationRow: The row type is self-contained.
// Three structural rules: row is self-contained (rendering any row does not require looking at other rows);
// For structural changes, the entire row is replaced (row.upserted), and for text growth, append (row.delta) is used; turn is the label on the row, not the container.
import { z } from "zod";
import { executionOutputPreviewSchema } from "../execution-output-preview.js";
import { timestampSchema } from "./core.js";
import { backgroundResultOriginMetaSchema, workflowLaunchMetaSchema } from "./workflow-row-meta.js";

// RowBase. rowId: a deterministic pure function that is monotonous, never reused, and event log within the session.
const rowBaseFields = {
  rowId: z.number(),
  turnId: z.string(),
  // canonical identity: Each line of the new CLI must be passed; optional is only used for compatibility with legacy frames.
  // entityId locates the persistent entity, productTurnId is the product turn and must not be reguessed by the UI.
  entityId: z.string().min(1).optional(),
  productTurnId: z.string().min(1).optional(),
  visibility: z.literal("visible").optional(),
  createdAt: timestampSchema,
  createdAtSeq: z.number(),
  // The default is all false; only keys that are true are delivered. canRewind is not in the payload (UI entry for rewind = editUserQuery).
  actions: z
    .object({
      canFork: z.literal(true).optional(),
      canEdit: z.literal(true).optional(),
      canRetry: z.literal(true).optional(),
      canRewindFiles: z.literal(true).optional(),
      editDisposition: z.enum(["rewind", "fork"]).optional(),
    })
    .optional(),
} as const;

export const rowActionsSchema = rowBaseFields.actions;
export type RowActions = NonNullable<z.infer<typeof rowActionsSchema>>;

