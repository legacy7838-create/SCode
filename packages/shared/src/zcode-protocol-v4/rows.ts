export const turnWorkSegmentSchema = z.object({
  segmentId: z.string().min(1),
  triggerEntityId: z.string().min(1).optional(),
  startedAt: timestampSchema,
  endedAt: timestampSchema.optional(),
  activeMs: z.number().nonnegative().optional(),
});
export type TurnWorkSegment = z.infer<typeof turnWorkSegmentSchema>;

// turnHeader: product turn boundary + authoritative hours + document summary for each round.
// Internal fold boundaries generated by the guide are expressed by workSegments; row ownership is still determined by the CLI, with zero client-side ownership logic.
export const turnHeaderRowSchema = z.object({
  ...rowBaseFields,
  kind: z.literal("turnHeader"),
  // workflowLaunch: The controlOnly wheel launched directly by the hub.
  // Documented Skew: Closed Enum Bonus → Old Desktop + New CLI This line is thrown when parse fails (same as below
  // backgroundSource: "workflow" (added in the same file), CLI and desktop are accepted in the same batch release.
  origin: z.enum([
    "userInput",
    "backgroundResult",
    "goalContinuation",
    "editRerun",
    "workflowLaunch",
  ]),
  // Execution semantics are arbitrated by the CLI projection; the UI may not infer based on input text or duration.
  // optional is only used for compatibility with old snapshots, and new turnHeader must be written explicitly.
  executionKind: z.enum(["agent", "controlOnly"]).optional(),
  // The command attribution of the current query and the number of historical rounds; optional is compatible with old transcript/snapshot.
  sourceCommandId: z.string().optional(),
  historyRoundCount: z.number().int().nonnegative().optional(),
  state: z.enum(["running", "completedSuccess", "completedInterrupted", "failed"]),
  startedAt: timestampSchema,
  endedAt: timestampSchema.optional(),
  // Authoritative hours: Exclude permission waits/user input waits/verifier waits.
  activeMs: z.number().optional(),
  // Guide does not cut product turn, but each accepted guide opens an independent visual work segment.
  // Normal turn defaults to maintain compatibility with old snapshots; once the guide appears, the CLI is responsible for fully projecting the first segment and subsequent segments.
  workSegments: z.array(turnWorkSegmentSchema).optional(),
  originMeta: backgroundResultOriginMetaSchema.optional(),
  // origin === "workflowLaunch"'s on-wheel presence (live projection source); juxtaposed with originMeta, without reusing its shape.
  workflowLaunch: workflowLaunchMetaSchema.optional(),
  fileChanges: z
    .object({
      additions: z.number(),
      deletions: z.number(),
      files: z.number(),
      state: z.enum(["active", "reverted"]).optional(),
    })
    .optional(),
});
export type TurnHeaderRow = z.infer<typeof turnHeaderRowSchema>;

// userInput. originMeta eliminates text sniffing.
export const userInputRowSchema = z.object({
  ...rowBaseFields,
  kind: z.literal("userInput"),
  text: z.string(),
  // text Starting from this subscript is the engine additional text (dwf ask endnote /
  // nudge), the GUI folds it into the default collapsed disclosure; 0 = the entire item; absent = none (old transcription, non-workflow sessions).
  epilogueStart: z.number().int().nonnegative().optional(),
  // workflowLaunch: The hub directly launches the user-visible row of the wheel.
  // The message text still enters text (the downgraded presentation of the old client/TUI is the standard English sentence); the new client uses the following
  // workflowLaunch metadata draws run cards instead of bubbles at the end of the wheel. The skew of closed set additions is the same as the turnHeader.origin annotation.
  origin: z.enum([
    "realUser",
    "backgroundResult",
    "goalContinuation",
    "mailbox",
    "synthetic",
    "workflowLaunch",
  ]),
  originMeta: z
    .object({
      // The same set of values ​​as backgroundResultOriginMetaSchema (including "workflow" of workflow run).
      backgroundSource: z.enum(["bash", "subagent", "workflow"]).optional(),
      workId: z.string().optional(),
      senderSessionId: z.string().optional(),
      senderLabel: z.string().optional(),
    })
    .optional(),
  // Present on the line origin === "workflowLaunch"; juxtaposed with originMeta, same as turnHeader.
  workflowLaunch: workflowLaunchMetaSchema.optional(),
  // Injected via turn-steer (guideModeTurnSteer).
  guided: z.literal(true).optional(),
  // realUser/guided is required; the system source is default. overlay closing anchor point.
  sourceCommandId: z.string().optional(),
  // edit/retry will generate a new sourceCommandId; this field is fixed to the canonical input root.
  // Used for one-time recovery of budget and other lineage judgments across reruns. Old transcript can be defaulted.
  rootSourceCommandId: z.string().optional(),
  // Submitter identity is written by CLI admission; old transcript can be defaulted.
  clientId: z.string().optional(),
  attachments: z
    .array(
      z.object({
        ref: z.string(),
        fileName: z.string(),
        mime: z.string(),
        bytes: z.number(),
        previewRef: z.string().optional(),
      }),
    )
    .optional(),
});
export type UserInputRow = z.infer<typeof userInputRowSchema>;

// assistantText / reasoning.
// Invariant: Only rows with state="streaming" can be appended; a normal new response must have a new rowId. The only exception is
