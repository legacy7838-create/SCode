/** The fixed system group id that sessions generated by cron scheduled tasks fall into by default. */
export const CRON_DEFAULT_GROUP_ID = "zcode-default-group-cron";

/** The fixed system group id that already-dispatched off-peak task sessions fall into by default (isomorphic to the cron group). */
export const OFF_PEAK_DEFAULT_GROUP_ID = "zcode-default-group-off-peak";

type CronTaskIdentity = Pick<ZCodeTaskMeta, "cronAutomationId"> & {
  automationId?: string;
};

/** Determines whether a task/session was produced by a scheduled task trigger. */
export function isCronTask(task: CronTaskIdentity): boolean {
  // The persistent task meta uses cronAutomationId; but the field name in the running state dispatch/old link is automationId.
  // If the UI only looks at the former, newly created or newly restored scheduled tasks will temporarily have no icon.
  return Boolean(task.cronAutomationId || task.automationId);
}

/** Determines whether a task/phantom row belongs to an off-peak task (only looks at the persisted meta flag; the UI does not query back into the off-peak store). */
export function isOffPeakTask(task: Pick<ZCodeTaskMeta, "offPeakTaskId">): boolean {
  return Boolean(task.offPeakTaskId);
}

