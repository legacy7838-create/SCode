// ---- Workspace level events (warming phase, asynchronous notification before task creation) ----

/**
 * Workspace-level events, used to deliver in real time the notifications the ZCode Agent pushes
 * asynchronously (such as slash commands and configOptions) to the UI before a task is created.
 *
 * Difference from ZCodeStreamEvent: ZCodeStreamEvent is bound to a concrete taskId, while
 * ZCodeWorkspaceEvent is bound to workspacePath and covers the gap before a task is created.
 */
export type ZCodeWorkspaceEvent =
  | ZCodeWorkspaceSlashCommandsUpdate
  | ZCodeWorkspaceConfigOptionsUpdate
  | ZCodeWorkspaceTaskListChanged
  | ZCodeWorkspaceSessionMessageSendRequested;

export interface ZCodeWorkspaceSlashCommandsUpdate {
  type: "workspace_slash_commands_update";
  workspacePath: string;
  /**
   * The `/` commands of a remote workspace are identity-isolated state and cannot be dispatched on
   * workspacePath alone. The same path may come from different SSH/WSL sessions, so with
   * workspaceIdentity attached the service/UI can converge on workspaceKey.
   */
  workspaceIdentity?: string;
  commands: ZCodeSlashCommand[];
}

export interface ZCodeWorkspaceConfigOptionsUpdate {
  type: "workspace_config_options_update";
  workspacePath: string;
  /**
   * Warmup configuration is likewise workspace-level identity state, so the remote scenario must carry workspaceIdentity along with the event.
   */
  workspaceIdentity?: string;
  configOptions: ZCodeConfigOption[];
}

export interface ZCodeWorkspaceTaskListChanged {
  type: "workspace_task_list_changed";
  workspacePath: string;
  workspaceIdentity?: string;
  taskId?: string;
  reason: "auto_archive" | "realtime_sync" | TaskRealtimeReason;
  taskMeta?: ZCodeTaskMeta;
  /** The Host has confirmed that this terminal state should produce a background unread; ordinary status/resume/snapshot convergence must not carry it. */
  unreadSignal?: "background_terminal";
}

export interface ZCodeWorkspaceSessionMessageSendRequested {
  type: "workspace_session_message_send_requested";
  workspacePath: string;
  workspaceIdentity?: string;
  request: {
    content: string;
    createdAt: string;
    fromSessionId: string;
    messageId: string;
    requestId: string;
    toSessionId: string;
  };
}

